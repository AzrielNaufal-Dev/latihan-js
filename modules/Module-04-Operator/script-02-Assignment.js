/*
 Operator Assignment 
 Penjelasan: Digunakan untuk menetap kan nilai ke Varible.
*/

// Assignment Dasar
let name = "Janggo"

// Assignment dan Penjumlahan
let a = 10
a += 20 // Output: 20 (sama halnya dengan `a = a + 20`)

// Assignment dan Pengurangan
let b = 20
b -= 10 // Output: 10 (sama halnya dengan `b = b - 10`)

// Assignment dan Perkalian
let x = 10
x *= 10 // Output: 100 (sama halnya dengan `x = x * 10`)

// Assignment dan Pembagian 
let z = 25
z /= 5 // Output: 25 (sama halnya dengan `z = z / 5`)

// Assignment dan Modulus
let y = 15
y %= 4 // Output: 3 (sama halnya dengan `y = y % 4`)
