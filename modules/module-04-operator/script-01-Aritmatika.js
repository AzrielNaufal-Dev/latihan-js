// Operator Aritmatika

// Penjumlahan +
let x = 5;
let y = 20;
let sum = x + y; // Output: 25

// pengurangan -

let a = 10;
let b = 5;
let diff = a - b; // Output: 5

// Perkalian *

let q = 10;
let w = 10;
let result = q * w; // Output: 100

// Pembagian /

let m = 25;
let n = 5;
let bagi = m / n; // Output: 5

// Modulus %

let r = 10;
let s = 3;
let mod = r % s; // Output: 1

// Eksponen **

let base = 2;
let exponent = 4;
let power = base ** exponent; // Output: 16

// Increment
let count = 10;
count++; // sama halnya dengan `count = count + 1`
console.log(count); // Output: 11

// Decrement
let countDown = 10
countDown-- // sama halnya dengan `countDown = countDown - 1`
console.log(countDown);
